#!/usr/bin/env bash
# Run ONCE from inside app_activity_det/ (next to ../app).
# Reuses the base firmware's board/hardware config so this app builds and flashes
# exactly like the original: same overlay, same partition map (so the LittleFS
# partition stays where it is), same MCUboot keys and sysbuild setup.
set -euo pipefail
cd "$(dirname "$0")"
BASE=../app
[ -d "$BASE" ] || { echo "ERROR: $BASE not found - run this inside app_activity_det/"; exit 1; }

echo "== 1. Copy hardware / bootloader config from $BASE"
for f in app.overlay pm_static.yml sysbuild.conf Kconfig.sysbuild VERSION qspi_w25.ini CMakePresets.json; do
  if [ -e "$BASE/$f" ]; then cp "$BASE/$f" . && echo "   copied $f"; else echo "   (skip: $f not in base)"; fi
done
for d in sysbuild keys; do
  if [ -d "$BASE/$d" ]; then rm -rf "./$d" && cp -R "$BASE/$d" "./$d" && echo "   copied $d/"; fi
done

echo "== 2. CMake pre-amble (board root / extra modules) from base CMakeLists.txt"
awk '/find_package[[:space:]]*\(Zephyr/ {exit} !/cmake_minimum_required/ {print}' "$BASE/CMakeLists.txt" > cmake_pre.cmake
echo "   wrote cmake_pre.cmake ($(wc -l < cmake_pre.cmake | tr -d ' ') lines)"
echo "   Lines in base CMakeLists.txt AFTER find_package that I did NOT copy - review them:"
awk 'f {print "     | " $0} /find_package[[:space:]]*\(Zephyr/ {f=1}' "$BASE/CMakeLists.txt" | grep -Ev '^\s*\|\s*$' | grep -Ev 'target_sources|src/' || true

echo "== 3. prj.conf = base prj.conf (minus app-defined Kconfig symbols) + app_overrides.conf"
syms=""
if [ -f "$BASE/Kconfig" ]; then
  syms=$(awk '/^[[:space:]]*(config|menuconfig)[[:space:]]+/ {print $2}' "$BASE/Kconfig" | paste -sd'|' -)
fi
{
  echo "# Generated by setup_from_base.sh from $BASE/prj.conf + app_overrides.conf"
  if [ -n "$syms" ]; then
    grep -Ev "^[[:space:]]*CONFIG_(${syms})([=[:space:]]|$)" "$BASE/prj.conf" | grep -Ev '^[[:space:]]*CONFIG_HPI_'
  else
    grep -Ev '^[[:space:]]*CONFIG_HPI_' "$BASE/prj.conf"
  fi
  echo
  echo "# ---- app_overrides.conf ----"
  cat app_overrides.conf
} > prj.conf
echo "   wrote prj.conf"
echo
echo "Done. Build it like the base app, e.g. from the workspace root:"
echo "   west build -p -b <your board> healthypi-move-fw/app_activity_det --sysbuild"
echo "If Kconfig complains about an undefined symbol, delete that line from prj.conf."